-- TutorON database schema (Supabase / Postgres + pgvector)
--
-- Run this in the Supabase SQL Editor (or via psql) to recreate the database
-- used by backend/ingest.py and backend/rag.py.

create extension if not exists vector;

-- ---------------------------------------------------------
-- Tables
-- ---------------------------------------------------------

create table if not exists public.documents (
    id   bigint generated by default as identity primary key,
    name text not null
);

create table if not exists public.chunks (
    id          bigint generated by default as identity primary key,
    document_id bigint references public.documents (id) on delete cascade,
    content     text not null,
    page_number integer,
    -- 1024 = native dimensionality of the bge-m3 embedding model
    embedding   vector(1024)
);

-- ---------------------------------------------------------
-- Semantic search (called via supabase.rpc("match_chunks") in backend/rag.py)
-- ---------------------------------------------------------

-- Changing the return columns requires dropping the old signature first —
-- "create or replace" cannot insert columns in the middle of a RETURNS TABLE.
drop function if exists public.match_chunks(vector, integer);

create function public.match_chunks(
    query_embedding vector,
    match_count integer
)
returns table (
    id            bigint,
    document_id   bigint,
    document_name text,
    content       text,
    page_number   integer,
    similarity    double precision
)
language sql
as $$
    select
        chunks.id,
        chunks.document_id,
        documents.name as document_name,
        chunks.content,
        chunks.page_number,
        1 - (chunks.embedding <=> query_embedding) as similarity
    from chunks
    join documents on documents.id = chunks.document_id
    order by chunks.embedding <=> query_embedding
    limit match_count;
$$;
